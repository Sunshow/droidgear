function isSchemaFactoryIdentifier(node) {
  return (
    ts.isIdentifier(node) &&
    (node.text === 'z' ||
      node.text === 's' ||
      node.text === 'Schema' ||
      node.text === 'schema')
  )
}

function isSchemaFactoryCall(node, method) {
  if (!ts.isCallExpression(node)) return false
  const callee = node.expression
  if (!ts.isPropertyAccessExpression(callee)) return false
  if (callee.name.text !== method) return false
  return isSchemaFactoryIdentifier(callee.expression)
}

function candidateName(node) {
  let current = node
  for (let depth = 0; depth < 6 && current; depth += 1) {
    const parent = current.parent
    if (!parent) break
    if (ts.isVariableDeclaration(parent) && ts.isIdentifier(parent.name))
      return parent.name.text
    if (ts.isPropertyDeclaration(parent) && ts.isIdentifier(parent.name))
      return parent.name.text
    if (ts.isPropertyAssignment(parent)) {
      const key = propertyKeyText(parent.name, parent.getSourceFile())
      if (key) return key
    }
    if (ts.isClassDeclaration(parent) && parent.name) return parent.name.text
    current = parent
  }
  return ''
}

function collectSchemaCandidates(context, files) {
  const candidates = []
  const seen = new Set()
  for (const file of files) {
    if (seen.has(file)) continue
    seen.add(file)
    const sourceFile = parseSourceFile(context, file)
    if (!sourceFile) continue
    const visit = node => {
      if (isSchemaFactoryCall(node, 'object')) {
        candidates.push({ file, node, name: candidateName(node) })
      }
      ts.forEachChild(node, visit)
    }
    visit(sourceFile)
  }
  return candidates
}

/** Resolve a property key, including `[CONSTANT]` computed keys. */
function resolvePropertyKey(context, name, sourceFile) {
  if (!name) return null
  if (
    ts.isIdentifier(name) ||
    ts.isStringLiteral(name) ||
    ts.isNumericLiteral(name)
  )
    return name.text
  if (ts.isComputedPropertyName(name)) {
    const evaluated = evaluateExpression(
      context,
      sourceFile?.fileName,
      name.expression
    )
    if (
      evaluated.ok &&
      (typeof evaluated.value === 'string' ||
        typeof evaluated.value === 'number')
    ) {
      return String(evaluated.value)
    }
    return null
  }
  return name.getText(sourceFile ?? undefined)
}

/**
 * Resolve `const { a, ...rest } = obj` bindings so schema spreads built from
 * destructured protocol fields (`...protocolFields`) keep working.
 */
function resolveDestructuredValue(context, sourceFile, localName) {
  let found = null
  const visit = node => {
    if (found) return
    if (
      ts.isVariableDeclaration(node) &&
      ts.isObjectBindingPattern(node.name)
    ) {
      const elements = node.name.elements
      const excluded = new Set()
      let restName = null
      for (const element of elements) {
        const local = ts.isIdentifier(element.name) ? element.name.text : null
        const key = element.propertyName
          ? ts.isIdentifier(element.propertyName) ||
            ts.isStringLiteral(element.propertyName)
            ? element.propertyName.text
            : null
          : local
        if (element.dotDotDotToken) restName = local
        else if (key) excluded.add(key)
      }
      for (const element of elements) {
        if (element.dotDotDotToken || !ts.isIdentifier(element.name)) continue
        if (element.name.text !== localName) continue
        const key = element.propertyName
          ? ts.isIdentifier(element.propertyName) ||
            ts.isStringLiteral(element.propertyName)
            ? element.propertyName.text
            : null
          : element.name.text
        if (key)
          found = {
            kind: 'member',
            file: sourceFile.fileName,
            container: node.initializer,
            key,
          }
      }
      if (restName === localName) {
        found = {
          kind: 'rest',
          file: sourceFile.fileName,
          container: node.initializer,
          excluded,
        }
      }
    }
    ts.forEachChild(node, visit)
  }
  visit(sourceFile)
  return found
}

/** Resolve an object-literal-like expression to { name, initializer, file } entries. */
function schemaObjectEntries(context, file, expression, depth = 0) {
  const entries = []
  if (!expression || depth > 6) return entries
  const sourceFile = parseSourceFile(context, file)
  const node = unwrap(expression)
  if (ts.isObjectLiteralExpression(node)) {
    for (const member of node.properties) {
      if (ts.isPropertyAssignment(member)) {
        const key = resolvePropertyKey(
          context,
          member.name,
          sourceFile ?? member.getSourceFile()
        )
        if (key)
          entries.push({ name: key, initializer: member.initializer, file })
      } else if (ts.isShorthandPropertyAssignment(member)) {
        entries.push({ name: member.name.text, initializer: member.name, file })
      } else if (ts.isSpreadAssignment(member)) {
        entries.push(
          ...schemaObjectEntries(context, file, member.expression, depth + 1)
        )
      }
    }
    return entries
  }
  if (ts.isCallExpression(node) && isSchemaFactoryCall(node, 'object')) {
    return schemaObjectEntries(context, file, node.arguments[0], depth + 1)
  }
  if (ts.isIdentifier(node)) {
    const resolved = resolveSymbol(context, sourceFile, node.text, 'value')
    if (resolved) {
      return schemaObjectEntries(
        context,
        resolved.file,
        resolved.node.initializer,
        depth + 1
      )
    }
    const destructured = resolveDestructuredValue(
      context,
      sourceFile,
      node.text
    )
    if (destructured) {
      const source = schemaObjectEntries(
        context,
        destructured.file,
        destructured.container,
        depth + 1
      )
      if (destructured.kind === 'member')
        return source.filter(entry => entry.name === destructured.key)
      return source.filter(entry => !destructured.excluded.has(entry.name))
    }
  }
  return entries
}

/** Resolve `SomeFields[key]` / `someObject.key` used as a field schema expression. */
function resolveSchemaMemberExpression(context, file, node, depth = 0) {
  if (depth > 6) return null
  const sourceFile = parseSourceFile(context, file)
  const unwrapped = unwrap(node)
  if (ts.isPropertyAccessExpression(unwrapped)) {
    return findSchemaMember(
      context,
      file,
      unwrapped.expression,
      unwrapped.name.text,
      depth + 1
    )
  }
  if (ts.isElementAccessExpression(unwrapped)) {
    const evaluated = evaluateExpression(
      context,
      file,
      unwrapped.argumentExpression
    )
    if (!evaluated.ok) return null
    return findSchemaMember(
      context,
      file,
      unwrapped.expression,
      String(evaluated.value),
      depth + 1
    )
  }
  void sourceFile
  return null
}

function findSchemaMember(context, file, container, key, depth) {
  const entries = schemaObjectEntries(context, file, container, depth)
  return entries.find(entry => entry.name === key) ?? null
}

function findConfigSchema(context, pkgDirs, fieldNames, sourcePath) {
  const dirs = [...new Set(pkgDirs.filter(Boolean))]
  if (dirs.length === 0) return null
  let best = null
  for (const dir of dirs) {
    const srcDir = existsSync(join(dir, 'src')) ? join(dir, 'src') : dir
    const candidates = collectSchemaCandidates(context, listTsFiles(srcDir))
    for (const candidate of candidates) {
      const entries = schemaObjectEntries(
        context,
        candidate.file,
        candidate.node.arguments[0]
      )
      const keys = entries.map(entry => entry.name)
      if (keys.length === 0) continue
      const matched = keys.filter(key => fieldNames.has(key)).length
      const unknown = keys.length - matched
      if (matched === 0 && fieldNames.size > 0) continue
      let score = matched * 10 - unknown * 4
      if (candidate.name === 'Config') score += 6
      else if (/Config$/.test(candidate.name)) score += 2
      if (sourcePath && candidate.file === sourcePath) score += 3
      if (fieldNames.size > 0) score += (matched / fieldNames.size) * 4
      if (!best || score > best.score) {
        best = { ...candidate, entries, score, matched, unknown }
      }
    }
  }
  if (!best) return null
  if (fieldNames.size > 0 && best.matched < Math.min(fieldNames.size, 1))
    return null
  return best
}


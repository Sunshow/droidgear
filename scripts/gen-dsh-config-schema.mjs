function loadCatalog(context) {
  if (context.catalog) return context.catalog
  const catalogPath = join(context.dshRoot, 'docs/config-catalog.zh.md')
  const sections = new Map()
  if (existsSync(catalogPath)) {
    const text = readFileSync(catalogPath, 'utf8')
    const pattern =
      /<!-- BEGIN GENERATED config-catalog:([^ ]+) -->\n([\s\S]*?)<!-- END GENERATED config-catalog:\1 -->/g
    let match
    while ((match = pattern.exec(text))) {
      const pkgName = match[1]
      const body = match[2]
      const sourceMatch = body.match(/- `source`: \[`([^`]+)`\]/)
      const codeMatch = body.match(/```ts config-catalog\n([\s\S]*?)```/)
      if (!sourceMatch || !codeMatch) continue
      const sourceRef = sourceMatch[1]
      const colon = sourceRef.lastIndexOf(':')
      sections.set(pkgName, {
        sourcePath: colon === -1 ? sourceRef : sourceRef.slice(0, colon),
        sourceLine: colon === -1 ? null : Number(sourceRef.slice(colon + 1)),
        code: codeMatch[1],
      })
    }
  }
  context.catalog = sections
  return sections
}

function catalogCodeInterfaces(context, pkgName, code) {
  const cached = context.catalogCode.get(pkgName)
  if (cached) return cached
  const fileName = `${pkgName}#config-catalog.ts`
  const sourceFile = ts.createSourceFile(
    fileName,
    code,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS
  )
  const interfaces = new Map()
  const types = new Map()
  for (const statement of sourceFile.statements) {
    if (ts.isInterfaceDeclaration(statement) && statement.name) {
      interfaces.set(statement.name.text, {
        file: fileName,
        node: statement,
        sourceFile,
      })
    } else if (ts.isTypeAliasDeclaration(statement) && statement.name) {
      types.set(statement.name.text, {
        file: fileName,
        node: statement,
        sourceFile,
      })
    }
  }
  // code-block ast nodes are bound to a synthetic SourceFile; keep it for getText
  const result = { sourceFile, interfaces, types }
  context.catalogCode.set(pkgName, result)
  return result
}


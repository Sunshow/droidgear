function resolveConfigForEntry(context, entryName) {
  const pkgName = resolvePackageName(context, entryName)
  if (!pkgName)
    return { fields: [], doc: '', sourcePath: null, schemaFound: false }
  const rest = entryName.slice(pkgName.length)
  if (rest.startsWith('/') && rest.length > 1) {
    return resolveModuleConfig(context, pkgName, rest.slice(1))
  }
  return resolveConfigForPackage(context, pkgName)
}

function resolveConfigForPackage(context, pkgName) {
  const cached = context.configCache.get(pkgName)
  if (cached) return cached
  const section = loadCatalog(context).get(pkgName)
  let result
  if (section) {
    result = resolveConfigFromCatalog(context, pkgName, section)
  } else {
    // DSH client plugins keep their user-facing settings in a separate
    // settings-namespace schema instead of the plugin Config documented by the
    // catalog; fall back to those schemas when the package declares a matching
    // `<Name>Settings`/`Config` interface plus schema.
    result = resolveSettingsConfig(context, pkgName)
  }
  context.configCache.set(pkgName, result)
  return result
}

/** Resolve a package's catalog-declared plugin Config to schema facts. */
function resolveConfigFromCatalog(context, pkgName, section) {
  const typeInfo = resolveCatalogType(context, pkgName, section)
  const fieldNames = new Set(typeInfo.fields.keys())
  const sourcePath = existsSync(join(context.dshRoot, section.sourcePath))
    ? join(context.dshRoot, section.sourcePath)
    : null
  const pkgDir =
    context.packageIndex.get(pkgName) ??
    (sourcePath ? packageDirOfFile(context, sourcePath) : null)
  const candidateDirs = configCandidateDirs(
    context,
    pkgDir,
    typeInfo.files,
    sourcePath
  )
  const schema = findConfigSchema(
    context,
    [...candidateDirs],
    fieldNames,
    sourcePath
  )
  let fields = []
  if (schema) {
    fields = schemaEntriesToFields(context, schema, typeInfo)
    if (fields.length === 0) fields = fallbackFieldsFromType(typeInfo)
  } else {
    fields = fallbackFieldsFromType(typeInfo)
    if (fields.length > 0) context.stats.schemaFallbackPackages.push(pkgName)
  }
  return {
    fields,
    doc: typeInfo.doc,
    sourcePath: section.sourcePath,
    schemaFound: Boolean(schema),
  }
}

/** Collect the package dirs that may hold a plugin's schemastery Config. */
function configCandidateDirs(context, pkgDir, typeFiles, sourcePath) {
  const dirs = new Set()
  if (pkgDir) dirs.add(pkgDir)
  for (const file of typeFiles) {
    const dir = packageDirOfFile(context, file)
    if (dir) dirs.add(dir)
  }
  if (sourcePath) {
    const sourceFile = parseSourceFile(context, sourcePath)
    if (sourceFile) {
      for (const statement of sourceFile.statements) {
        if (!ts.isImportDeclaration(statement)) continue
        const pkgTarget = resolvePackageName(
          context,
          statement.moduleSpecifier.text
        )
        const dir = pkgTarget ? context.packageIndex.get(pkgTarget) : null
        if (dir) dirs.add(dir)
      }
    }
  }
  return dirs
}

function schemaEntriesToFields(context, schema, typeInfo, options = {}) {
  const fields = []
  for (const entry of schema.entries) {
    const info = analyzeSchema(context, entry.file, entry.initializer)
    const typeField = typeInfo.fields.get(entry.name)
    const secretInSchema = schemaHasSecretRole(
      context,
      entry.file,
      entry.initializer
    )
    fields.push(
      buildField(entry.name, info, typeField, secretInSchema, options)
    )
  }
  return fields
}

/**
 * Subpath plugin entries (`<pkg>/<export>`) own their own Config and are not
 * documented as a top-level catalog section; resolve the export's source file
 * from the package.json `exports` map and extract it like a standalone module.
 */
function resolveModuleConfig(context, pkgName, subpath) {
  const cacheKey = `${pkgName}/${subpath}`
  const cached = context.configCache.get(cacheKey)
  if (cached) return cached
  const pkgDir = context.packageIndex.get(pkgName)
  const modulePath = resolveSubpathSourceFile(context, pkgDir, subpath)
  let result = { fields: [], doc: '', sourcePath: null, schemaFound: false }
  if (modulePath) {
    const sourceFile = parseSourceFile(context, modulePath)
    if (sourceFile) {
      const typeInfo = resolveModuleType(context, sourceFile, modulePath)
      const fieldNames = new Set(typeInfo.fields.keys())
      const candidateDirs = configCandidateDirs(
        context,
        pkgDir,
        typeInfo.files,
        modulePath
      )
      const schema = findConfigSchema(
        context,
        [...candidateDirs],
        fieldNames,
        modulePath
      )
      let fields = []
      if (schema) {
        fields = schemaEntriesToFields(context, schema, typeInfo)
        if (fields.length === 0) fields = fallbackFieldsFromType(typeInfo)
      } else {
        fields = fallbackFieldsFromType(typeInfo)
      }
      result = {
        fields,
        doc: typeInfo.doc,
        sourcePath: modulePath,
        schemaFound: Boolean(schema),
      }
    }
  }
  context.configCache.set(cacheKey, result)
  return result
}

/** Find the source file backing a `package.json` `exports` subpath. */
function resolveSubpathSourceFile(context, pkgDir, subpath) {
  if (!pkgDir) return null
  const pkg = packageJsonOf(context, pkgDir)
  const exportsMap = pkg?.exports
  if (!exportsMap || typeof exportsMap !== 'object') return null
  const keys = [`./${subpath}`, `./${subpath}/*`]
  for (const key of keys) {
    const entry = exportsMap[key]
    if (!entry) continue
    const paths = []
    if (typeof entry === 'string') paths.push(entry)
    else
      for (const value of Object.values(entry))
        if (typeof value === 'string') paths.push(value)
    for (const candidate of paths) {
      const source = join(pkgDir, candidate)
      if (existsSync(source) && source.endsWith('.ts')) return source
      // `./lib/types/<name>.d.ts` or `./lib/<name>.js` -> `src/<name>.ts`
      const relative = candidate
        .replace(/^\.\//, '')
        .replace(/^lib\/(types\/)?/, '')
        .replace(/\.(d\.ts|js|mjs|cjs)$/, '')
      for (const extension of ['.ts', '.mts', '.tsx']) {
        const guess = join(pkgDir, 'src', `${relative}${extension}`)
        if (existsSync(guess)) return guess
      }
    }
  }
  return null
}

/** Resolve the Config/`*Settings` declaration of a standalone module file. */
function resolveModuleType(context, sourceFile, modulePath) {
  const collector = createTypeCollector(context)
  const exportedTypes = []
  const exportedValues = []
  for (const statement of sourceFile.statements) {
    if (ts.isInterfaceDeclaration(statement) && statement.name) {
      exportedTypes.push(statement)
    } else if (ts.isTypeAliasDeclaration(statement) && statement.name) {
      exportedTypes.push(statement)
    } else if (ts.isVariableStatement(statement)) {
      for (const declaration of statement.declarationList.declarations) {
        if (ts.isIdentifier(declaration.name) && declaration.initializer)
          exportedValues.push(declaration)
      }
    }
  }
  const preferred =
    exportedTypes.find(node => node.name.text === 'Config') ??
    exportedTypes.find(
      node => /Config$/.test(node.name.text) && hasExportModifier(node)
    ) ??
    exportedTypes.find(
      node => /Settings$/.test(node.name.text) && hasExportModifier(node)
    ) ??
    exportedTypes.find(node => hasExportModifier(node))
  if (!preferred)
    return { doc: '', fields: new Map(), files: new Set([modulePath]) }
  const doc = jsdocText(preferred)
  if (ts.isInterfaceDeclaration(preferred)) {
    for (const member of preferred.members ?? []) {
      const field = typeFieldFromMember(context, member, sourceFile)
      if (field && !collector.fields.has(field.name))
        collector.fields.set(field.name, field)
    }
    for (const heritage of preferred.heritageClauses ?? []) {
      for (const type of heritage.types)
        collector.collectHeritage(modulePath, type, 0)
    }
  } else if (ts.isTypeAliasDeclaration(preferred)) {
    collector.collectTypeNode(modulePath, preferred.type, 0)
  }
  collector.files.add(modulePath)
  return { doc, fields: collector.fields, files: collector.files }
}

/**
 * Client settings fallback: find an exported `XSettings`/`Config` interface with
 * a matching `XSettingsSchema`/`XSettingsFields` (or same-name) schemastery
 * declaration in the same package. Used only when the catalog declares no plugin
 * Config, so it cannot shadow a documented plugin schema.
 */
function resolveSettingsConfig(context, pkgName) {
  const pkgDir = context.packageIndex.get(pkgName)
  const empty = { fields: [], doc: '', sourcePath: null, schemaFound: false }
  if (!pkgDir) return empty
  const srcDir = existsSync(join(pkgDir, 'src')) ? join(pkgDir, 'src') : pkgDir
  let best = null
  for (const file of listTsFiles(srcDir)) {
    const sourceFile = parseSourceFile(context, file)
    if (!sourceFile) continue
    const interfaces = new Map()
    const schemas = new Map()
    for (const statement of sourceFile.statements) {
      if (
        ts.isInterfaceDeclaration(statement) &&
        statement.name &&
        hasExportModifier(statement)
      ) {
        interfaces.set(statement.name.text, statement)
      } else if (
        ts.isTypeAliasDeclaration(statement) &&
        statement.name &&
        hasExportModifier(statement)
      ) {
        interfaces.set(statement.name.text, statement)
      } else if (
        ts.isVariableStatement(statement) &&
        hasExportModifier(statement)
      ) {
        for (const declaration of statement.declarationList.declarations) {
          if (!ts.isIdentifier(declaration.name) || !declaration.initializer)
            continue
          schemas.set(declaration.name.text, declaration)
        }
      }
    }
    for (const [interfaceName, interfaceNode] of interfaces) {
      const schemaDeclaration =
        schemas.get(`${interfaceName}Schema`) ??
        schemas.get(`${interfaceName}Fields`) ??
        schemas.get(interfaceName)
      if (!schemaDeclaration) continue
      if (!/(Settings|Config)$/.test(interfaceName)) continue
      if (
        !ts.isInterfaceDeclaration(interfaceNode) &&
        !ts.isTypeAliasDeclaration(interfaceNode)
      )
        continue
      const collector = createTypeCollector(context)
      if (ts.isInterfaceDeclaration(interfaceNode)) {
        for (const member of interfaceNode.members ?? []) {
          const field = typeFieldFromMember(context, member, sourceFile)
          if (field && !collector.fields.has(field.name))
            collector.fields.set(field.name, field)
        }
        for (const heritage of interfaceNode.heritageClauses ?? []) {
          for (const type of heritage.types)
            collector.collectHeritage(file, type, 0)
        }
      } else {
        collector.collectTypeNode(file, interfaceNode.type, 0)
      }
      const fields = schemaEntriesToFields(
        context,
        {
          file,
          entries: schemaObjectEntries(
            context,
            file,
            schemaDeclaration.initializer
          ),
          name: interfaceName,
        },
        { fields: collector.fields, files: collector.files },
        { forceVolatile: true }
      )
      if (fields.length === 0) continue
      let score = fields.length
      if (/Settings$/.test(interfaceName)) score += 8
      if (interfaceName === 'Config') score += 4
      if (/settings/i.test(file)) score += 6
      if (!best || score > best.score) {
        best = {
          score,
          fields,
          doc: jsdocText(interfaceNode),
          sourcePath: file,
          schemaFound: true,
        }
      }
    }
  }
  if (!best) return empty
  return {
    fields: best.fields,
    doc: best.doc,
    sourcePath: best.sourcePath,
    schemaFound: best.schemaFound,
  }
}

/** True when a schemastery subtree declares `role('secret')` anywhere. */
function schemaHasSecretRole(context, file, node, depth = 0) {
  if (!node || depth > 10) return false
  const sourceFile = parseSourceFile(context, file)
  const unwrapped = unwrap(node)
  if (!unwrapped) return false
  if (
    ts.isCallExpression(unwrapped) &&
    ts.isPropertyAccessExpression(unwrapped.expression)
  ) {
    const method = unwrapped.expression.name.text
    if (method === 'role') {
      const value = unwrapped.arguments[0]
      if (value && ts.isStringLiteral(value) && value.text === 'secret')
        return true
    }
    if (
      schemaHasSecretRole(
        context,
        file,
        unwrapped.expression.expression,
        depth + 1
      )
    )
      return true
    for (const argument of unwrapped.arguments) {
      if (schemaHasSecretRole(context, file, argument, depth + 1)) return true
    }
    return false
  }
  if (ts.isIdentifier(unwrapped)) {
    const resolved = resolveSymbol(context, sourceFile, unwrapped.text, 'value')
    if (resolved)
      return schemaHasSecretRole(
        context,
        resolved.file,
        resolved.node.initializer,
        depth + 1
      )
    return false
  }
  if (ts.isArrayLiteralExpression(unwrapped)) {
    return unwrapped.elements.some(element =>
      schemaHasSecretRole(context, file, element, depth + 1)
    )
  }
  if (ts.isObjectLiteralExpression(unwrapped)) {
    return unwrapped.properties.some(
      property =>
        ts.isPropertyAssignment(property) &&
        schemaHasSecretRole(context, file, property.initializer, depth + 1)
    )
  }
  return false
}

function buildField(name, info, typeField, secretInSchema, options = {}) {
  const typeFallback = kindFromTypeText(
    typeField?.typeText ?? '',
    Boolean(typeField?.volatile)
  )
  const enumValues =
    info.enumValues ??
    (typeFallback.kind === 'enum' ? typeFallback.enumValues : [])
  let kind =
    info.kind ?? (typeFallback.kind !== 'json' ? typeFallback.kind : 'json')
  if (kind === 'enum' && enumValues.length === 0) kind = 'json'
  const defaultValue = info.default.has
    ? normalizeJsonValue(info.default.value)
    : null
  return {
    name,
    kind,
    default: defaultValue,
    nullable: Boolean(info.nullable || typeFallback.nullable),
    enumValues: kind === 'enum' ? enumValues : [],
    volatile: Boolean(
      info.volatile || typeField?.volatile || options.forceVolatile
    ),
    secret: Boolean(info.secret || secretInSchema),
    description: cleanDoc(typeField?.doc || info.description),
  }
}
function normalizeJsonValue(value) {
  if (value === undefined) return null
  if (typeof value === 'number' && !Number.isFinite(value)) return null
  return value
}

function fallbackFieldsFromType(typeInfo) {
  const fields = []
  for (const typeField of typeInfo.fields.values()) {
    // Runtime-only seams (`openTextFile: (path) => Promise<void>`, `Stream`, ...)
    // are excluded from the runtime schema and cannot be set through the patch
    // file, so an interface-only fallback must not offer them as config fields.
    if (/=>|\bfunction\b|\bAbortSignal\b/.test(typeField.typeText)) continue
    const fallback = kindFromTypeText(
      typeField.typeText,
      Boolean(typeField.volatile)
    )
    fields.push({
      name: typeField.name,
      kind: fallback.kind,
      default: null,
      nullable: fallback.nullable,
      enumValues: fallback.kind === 'enum' ? fallback.enumValues : [],
      volatile: Boolean(typeField.volatile),
      secret: false,
      description: cleanDoc(typeField.doc),
    })
  }
  return fields
}


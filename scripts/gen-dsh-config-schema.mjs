function findLocalTypeDeclaration(context, sourceFile, name) {
  const found = []
  const visit = node => {
    if (ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)) {
      if (node.name?.text === name) found.push(node)
    }
    ts.forEachChild(node, visit)
  }
  visit(sourceFile)
  return found.find(node => hasExportModifier(node)) ?? found[0] ?? null
}

function findLocalValueDeclaration(context, sourceFile, name) {
  let result = null
  const visit = node => {
    if (result) return
    if (
      ts.isVariableDeclaration(node) &&
      ts.isIdentifier(node.name) &&
      node.name.text === name
    ) {
      result = node
      return
    }
    ts.forEachChild(node, visit)
  }
  visit(sourceFile)
  return result
}

function importTargetsForName(context, sourceFile, name) {
  const targets = []
  const visit = node => {
    if (ts.isImportDeclaration(node)) {
      const clause = node.importClause
      if (clause) {
        if (clause.name && clause.name.text === name && node.moduleSpecifier) {
          targets.push({
            specifier: node.moduleSpecifier.text,
            imported: 'default',
          })
        }
        const bindings = clause.namedBindings
        if (bindings && ts.isNamedImports(bindings)) {
          for (const element of bindings.elements) {
            if (element.name.text === name) {
              targets.push({
                specifier: node.moduleSpecifier.text,
                imported: element.propertyName?.text ?? element.name.text,
              })
            }
          }
        }
      }
    } else if (
      ts.isExportDeclaration(node) &&
      node.specifiers &&
      node.moduleSpecifier
    ) {
      for (const element of node.specifiers) {
        if (ts.isExportSpecifier(element) && element.name.text === name) {
          targets.push({
            specifier: node.moduleSpecifier.text,
            imported: element.propertyName?.text ?? element.name.text,
          })
        }
      }
    }
    ts.forEachChild(node, visit)
  }
  visit(sourceFile)
  return targets
}

function resolveModuleFile(context, fromFile, specifier) {
  if (!specifier.startsWith('.')) return null
  const base = resolve(dirname(fromFile), specifier)
  const candidates = [
    base,
    `${base}.ts`,
    `${base}.mts`,
    join(base, 'index.ts'),
    join(base, 'index.mts'),
  ]
  for (const candidate of candidates) {
    if (existsSync(candidate) && statSync(candidate).isFile()) return candidate
  }
  return null
}

function packageSymbols(context, pkgDir) {
  const cached = context.pkgSymbols.get(pkgDir)
  if (cached) return cached
  const symbols = { types: new Map(), values: new Map(), files: [] }
  const srcDir = existsSync(join(pkgDir, 'src')) ? join(pkgDir, 'src') : pkgDir
  const files = listTsFiles(srcDir)
  symbols.files = files
  for (const file of files) {
    const sourceFile = parseSourceFile(context, file)
    if (!sourceFile) continue
    for (const statement of sourceFile.statements) {
      if (
        ts.isInterfaceDeclaration(statement) ||
        ts.isTypeAliasDeclaration(statement)
      ) {
        const name = statement.name?.text
        if (name && !symbols.types.has(name))
          symbols.types.set(name, { file, node: statement })
        continue
      }
      if (ts.isClassDeclaration(statement) && statement.name) {
        if (!symbols.types.has(statement.name.text)) {
          symbols.types.set(statement.name.text, { file, node: statement })
        }
        continue
      }
      if (ts.isVariableStatement(statement)) {
        for (const declaration of statement.declarationList.declarations) {
          if (
            ts.isIdentifier(declaration.name) &&
            !symbols.values.has(declaration.name.text)
          ) {
            symbols.values.set(declaration.name.text, {
              file,
              node: declaration,
            })
          }
        }
      }
      if (ts.isExportDeclaration(statement) && statement.moduleSpecifier) {
        const specifier = statement.moduleSpecifier.text
        if (!ts.isStringLiteral(statement.moduleSpecifier)) continue
        const targetFile = resolveModuleFile(context, file, specifier)
        if (!targetFile) continue
        const targetSource = parseSourceFile(context, targetFile)
        if (!targetSource) continue
        // Re-exported symbols: record the original declaration so
        // `import { Config } from '<pkg>'` resolves even when index.ts only
        // forwards from ./config.ts.
        for (const targetStatement of targetSource.statements) {
          if (
            ts.isInterfaceDeclaration(targetStatement) ||
            ts.isTypeAliasDeclaration(targetStatement)
          ) {
            const name = targetStatement.name?.text
            if (name && !symbols.types.has(name)) {
              symbols.types.set(name, {
                file: targetFile,
                node: targetStatement,
              })
            }
          } else if (ts.isVariableStatement(targetStatement)) {
            for (const declaration of targetStatement.declarationList
              .declarations) {
              if (
                ts.isIdentifier(declaration.name) &&
                !symbols.values.has(declaration.name.text)
              ) {
                symbols.values.set(declaration.name.text, {
                  file: targetFile,
                  node: declaration,
                })
              }
            }
          }
        }
      }
    }
  }
  context.pkgSymbols.set(pkgDir, symbols)
  return symbols
}

function resolveSymbol(context, sourceFile, name, kind) {
  if (!sourceFile) return null
  const local =
    kind === 'value'
      ? findLocalValueDeclaration(context, sourceFile, name)
      : findLocalTypeDeclaration(context, sourceFile, name)
  if (local) return { file: sourceFile.fileName, node: local }
  for (const target of importTargetsForName(context, sourceFile, name)) {
    const imported = target.imported
    if (imported === 'default') continue
    const targetFile = resolveModuleFile(
      context,
      sourceFile.fileName,
      target.specifier
    )
    if (targetFile) {
      const targetSource = parseSourceFile(context, targetFile)
      const node =
        kind === 'value'
          ? findLocalValueDeclaration(context, targetSource, imported)
          : findLocalTypeDeclaration(context, targetSource, imported)
      if (node) return { file: targetFile, node }
      continue
    }
    const pkgName = resolvePackageName(context, target.specifier)
    if (!pkgName) continue
    const pkgDir = context.packageIndex.get(pkgName)
    const symbols = packageSymbols(context, pkgDir)
    const hit =
      kind === 'value'
        ? symbols.values.get(imported)
        : symbols.types.get(imported)
    if (hit) return { file: hit.file, node: hit.node }
  }
  return null
}


function createEmptySchemaInfo() {
  return {
    kind: null,
    enumValues: null,
    nullable: false,
    volatile: false,
    secret: false,
    description: '',
    default: { has: false, value: null },
  }
}

function mergeSchemaInfo(base, modifierInfo) {
  const merged = { ...base }
  if (modifierInfo.kind) merged.kind = modifierInfo.kind
  if (modifierInfo.enumValues) merged.enumValues = modifierInfo.enumValues
  if (modifierInfo.nullable) merged.nullable = true
  if (modifierInfo.volatile) merged.volatile = true
  if (modifierInfo.secret) merged.secret = true
  if (modifierInfo.description) merged.description = modifierInfo.description
  if (modifierInfo.default.has) merged.default = modifierInfo.default
  return merged
}

function analyzeSchema(context, file, node, depth = 0) {
  const info = createEmptySchemaInfo()
  if (!node || depth > 8) return info
  const sourceFile = parseSourceFile(context, file)
  let current = unwrap(node)
  const modifiers = []
  let base = null
  while (current) {
    if (
      ts.isCallExpression(current) &&
      ts.isPropertyAccessExpression(current.expression)
    ) {
      const method = current.expression.name.text
      const receiver = unwrap(current.expression.expression)
      if (BASE_METHODS.has(method) && isSchemaFactoryIdentifier(receiver)) {
        base = baseSchemaInfo(context, file, method, current.arguments)
        break
      }
      if (
        isSchemaFactoryCall(receiver, 'object') ||
        isSchemaFactoryCall(receiver, 'string') ||
        isSchemaFactoryCall(receiver, 'number') ||
        isSchemaFactoryCall(receiver, 'boolean')
      ) {
        // e.g. z.object({...}).extend(...) — the receiver is the base call, which
        // the loop will reach on the next iteration.
      }
      modifiers.push({ method, args: current.arguments })
      current = receiver
      continue
    }
    if (
      ts.isElementAccessExpression(current) ||
      ts.isPropertyAccessExpression(current)
    ) {
      const member = resolveSchemaMemberExpression(context, file, current)
      if (member)
        base = analyzeSchema(
          context,
          member.file,
          member.initializer,
          depth + 1
        )
      break
    }
    if (ts.isIdentifier(current)) {
      const resolved = resolveSymbol(context, sourceFile, current.text, 'value')
      if (resolved) {
        base = analyzeSchema(
          context,
          resolved.file,
          resolved.node.initializer,
          depth + 1
        )
      }
      break
    }
    break
  }
  let merged = base ?? info
  for (let index = modifiers.length - 1; index >= 0; index -= 1) {
    merged = mergeSchemaInfo(
      merged,
      modifierInfo(context, file, modifiers[index])
    )
  }
  return merged
}

function modifierInfo(context, file, modifier) {
  const info = createEmptySchemaInfo()
  if (modifier.method === 'volatile') info.volatile = true
  if (modifier.method === 'nullable') info.nullable = true
  if (modifier.method === 'role') {
    const value = modifier.args[0]
    if (value && ts.isStringLiteral(value) && value.text === 'secret')
      info.secret = true
  }
  if (modifier.method === 'default') {
    const evaluation = evaluateExpression(context, file, modifier.args[0])
    info.default = evaluation.ok
      ? { has: true, value: evaluation.value }
      : { has: false, value: null }
  }
  if (modifier.method === 'description') {
    const value = modifier.args[0]
    if (value && ts.isStringLiteral(value))
      info.description = cleanDoc(value.text)
  }
  return info
}

function baseSchemaInfo(context, file, method, args) {
  const info = createEmptySchemaInfo()
  switch (method) {
    case 'string':
    case 'url':
    case 'uuid':
    case 'email':
      info.kind = 'string'
      return info
    case 'number':
    case 'natural':
    case 'int':
    case 'percent':
      info.kind = 'number'
      return info
    case 'boolean':
      info.kind = 'boolean'
      return info
    case 'union':
    case 'enum': {
      const enumValues = extractEnumValues(
        context,
        file,
        method === 'enum' ? [args[0]] : args
      )
      if (enumValues) {
        info.kind = 'enum'
        info.enumValues = enumValues
        return info
      }
      if (method === 'union') {
        return unionSchemaInfo(context, file, args[0])
      }
      info.kind = 'json'
      return info
    }
    case 'const':
    case 'literal': {
      const value = args[0]
      const evaluated = evaluateExpression(context, file, value)
      if (evaluated.ok) {
        if (typeof evaluated.value === 'string') {
          info.kind = 'enum'
          info.enumValues = [evaluated.value]
        } else if (typeof evaluated.value === 'number') {
          info.kind = 'number'
        } else if (typeof evaluated.value === 'boolean') {
          info.kind = 'boolean'
        } else {
          info.kind = 'json'
          if (evaluated.value === null) info.nullable = true
        }
        return info
      }
      info.kind = 'json'
      return info
    }
    case 'null':
      info.kind = 'json'
      info.nullable = true
      return info
    default:
      info.kind = 'json'
      return info
  }
}

function unionSchemaInfo(context, file, argument) {
  const info = createEmptySchemaInfo()
  const branches = resolveArrayLike(context, file, argument)
  if (!branches) {
    info.kind = 'json'
    return info
  }
  const nonNullBranches = []
  let nullable = false
  for (const branch of branches) {
    if (isNullishBranch(context, file, branch)) {
      if (isNullBranch(branch)) nullable = true
      continue
    }
    nonNullBranches.push(branch)
  }
  info.nullable = nullable
  if (nonNullBranches.length === 0) {
    info.kind = 'json'
    return info
  }
  const branchInfos = nonNullBranches.map(branch =>
    analyzeSchema(context, file, branch)
  )
  const kinds = new Set(
    branchInfos.map(branchInfo => branchInfo.kind).filter(Boolean)
  )
  if (kinds.size === 1) {
    info.kind = [...kinds][0]
    if (info.kind === 'enum') {
      const values = branchInfos.flatMap(
        branchInfo => branchInfo.enumValues ?? []
      )
      info.enumValues = values.length > 0 ? values : null
      if (!info.enumValues) info.kind = 'json'
    }
  } else {
    info.kind = 'json'
  }
  for (const branchInfo of branchInfos) {
    if (branchInfo.volatile) info.volatile = true
    if (branchInfo.secret) info.secret = true
  }
  return info
}

function isNullBranch(node) {
  const unwrapped = unwrap(node)
  if (!ts.isCallExpression(unwrapped)) return false
  if (!ts.isPropertyAccessExpression(unwrapped.expression)) return false
  return unwrapped.expression.name.text === 'null'
}

function isNullishBranch(context, file, node) {
  const unwrapped = unwrap(node)
  if (
    ts.isCallExpression(unwrapped) &&
    ts.isPropertyAccessExpression(unwrapped.expression)
  ) {
    const method = unwrapped.expression.name.text
    if (method === 'null') return true
    if (method === 'const' || method === 'literal') {
      const evaluation = evaluateExpression(
        context,
        file,
        unwrapped.arguments[0]
      )
      return (
        evaluation.ok &&
        (evaluation.value === null || evaluation.value === undefined)
      )
    }
    return false
  }
  if (ts.isIdentifier(unwrapped) && unwrapped.text === 'undefined') return true
  return false
}

function resolveArrayLike(context, file, node) {
  const sourceFile = parseSourceFile(context, file)
  const unwrapped = unwrap(node)
  if (!unwrapped) return null
  if (ts.isArrayLiteralExpression(unwrapped)) return unwrapped.elements
  if (ts.isIdentifier(unwrapped)) {
    const resolved = resolveSymbol(context, sourceFile, unwrapped.text, 'value')
    if (resolved)
      return resolveArrayLike(context, resolved.file, resolved.node.initializer)
  }
  if (ts.isCallExpression(unwrapped)) {
    // Object.keys(...) / Object.values(...) cannot be enumerated statically.
    if (
      ts.isPropertyAccessExpression(unwrapped.expression) &&
      ts.isIdentifier(unwrapped.expression.expression) &&
      unwrapped.expression.expression.text === 'Object'
    ) {
      return null
    }
  }
  return null
}

function extractEnumValues(context, file, argumentNodes) {
  const values = []
  const push = value => {
    if (Array.isArray(value)) {
      for (const inner of value) push(inner)
      return
    }
    if (typeof value === 'string' && !values.includes(value)) values.push(value)
  }
  for (const argument of argumentNodes) {
    const branches = resolveArrayLike(context, file, argument)
    if (!branches) return null
    for (const branch of branches) {
      const value = branchEnumValue(context, file, branch)
      if (value === undefined) return null
      push(value)
    }
  }
  return values.length > 0 ? values : null
}

function branchEnumValue(context, file, node) {
  const unwrapped = unwrap(node)
  if (
    ts.isStringLiteral(unwrapped) ||
    ts.isNoSubstitutionTemplateLiteral(unwrapped)
  ) {
    return unwrapped.text
  }
  if (ts.isSpreadElement(unwrapped)) {
    const inner = resolveArrayLike(context, file, unwrapped.expression)
    if (!inner) return undefined
    const values = []
    for (const element of inner) {
      const value = branchEnumValue(context, file, element)
      if (value === undefined) return undefined
      values.push(value)
    }
    return values
  }
  if (
    ts.isCallExpression(unwrapped) &&
    ts.isPropertyAccessExpression(unwrapped.expression)
  ) {
    const method = unwrapped.expression.name.text
    if (
      (method === 'const' || method === 'literal') &&
      isSchemaFactoryIdentifier(unwrapped.expression.expression)
    ) {
      const arg = unwrapped.arguments[0]
      if (
        arg &&
        (ts.isStringLiteral(arg) || ts.isNoSubstitutionTemplateLiteral(arg))
      )
        return arg.text
      return undefined
    }
    if (
      method === 'enum' &&
      isSchemaFactoryIdentifier(unwrapped.expression.expression)
    ) {
      return extractEnumValues(context, file, unwrapped.arguments) ?? undefined
    }
    if (
      method === 'union' &&
      isSchemaFactoryIdentifier(unwrapped.expression.expression)
    ) {
      const values = extractEnumValues(context, file, unwrapped.arguments)
      return values ?? undefined
    }
  }
  if (ts.isIdentifier(unwrapped)) {
    const resolved = resolveSymbol(
      context,
      parseSourceFile(context, file),
      unwrapped.text,
      'value'
    )
    if (resolved)
      return branchEnumValue(context, resolved.file, resolved.node.initializer)
  }
  return undefined
}

/* -------------------------------------------------------------------------- */
/* Default value evaluation                                                   */
/* -------------------------------------------------------------------------- */

function evaluateExpression(context, file, node, depth = 0) {
  if (!node || depth > 8) return { ok: false }
  const sourceFile = parseSourceFile(context, file)
  const unwrapped = unwrap(node)
  if (!unwrapped) return { ok: false }
  if (ts.isNumericLiteral(unwrapped)) {
    const value = Number(unwrapped.text.replace(/_/g, ''))
    return Number.isNaN(value) ? { ok: false } : { ok: true, value }
  }
  if (
    ts.isStringLiteral(unwrapped) ||
    ts.isNoSubstitutionTemplateLiteral(unwrapped)
  ) {
    return { ok: true, value: unwrapped.text }
  }
  if (unwrapped.kind === ts.SyntaxKind.TrueKeyword)
    return { ok: true, value: true }
  if (unwrapped.kind === ts.SyntaxKind.FalseKeyword)
    return { ok: true, value: false }
  if (unwrapped.kind === ts.SyntaxKind.NullKeyword)
    return { ok: true, value: null }
  if (ts.isTemplateExpression(unwrapped)) {
    let result = unwrapped.head.text
    for (const span of unwrapped.templateSpans) {
      const evaluated = evaluateExpression(
        context,
        file,
        span.expression,
        depth + 1
      )
      if (!evaluated.ok) return { ok: false }
      result += String(evaluated.value) + span.literal.text
    }
    return { ok: true, value: result }
  }
  if (ts.isPrefixUnaryExpression(unwrapped)) {
    const evaluated = evaluateExpression(
      context,
      file,
      unwrapped.operand,
      depth + 1
    )
    if (!evaluated.ok) return { ok: false }
    if (unwrapped.operator === ts.SyntaxKind.MinusToken)
      return { ok: true, value: -evaluated.value }
    if (unwrapped.operator === ts.SyntaxKind.PlusToken)
      return { ok: true, value: +evaluated.value }
    return { ok: false }
  }
  if (ts.isBinaryExpression(unwrapped)) {
    const left = evaluateExpression(context, file, unwrapped.left, depth + 1)
    const right = evaluateExpression(context, file, unwrapped.right, depth + 1)
    if (!left.ok || !right.ok) return { ok: false }
    switch (unwrapped.operatorToken.kind) {
      case ts.SyntaxKind.PlusToken:
        return { ok: true, value: left.value + right.value }
      case ts.SyntaxKind.MinusToken:
        return { ok: true, value: left.value - right.value }
      case ts.SyntaxKind.AsteriskToken:
        return { ok: true, value: left.value * right.value }
      case ts.SyntaxKind.SlashToken:
        return { ok: true, value: left.value / right.value }
      case ts.SyntaxKind.PercentToken:
        return { ok: true, value: left.value % right.value }
      case ts.SyntaxKind.AsteriskAsteriskToken:
        return { ok: true, value: left.value ** right.value }
      case ts.SyntaxKind.QuestionQuestionToken:
        return { ok: true, value: left.value ?? right.value }
      case ts.SyntaxKind.BarBarToken:
        return { ok: true, value: left.value || right.value }
      case ts.SyntaxKind.AmpersandAmpersandToken:
        return { ok: true, value: left.value && right.value }
      default:
        return { ok: false }
    }
  }
  if (ts.isArrayLiteralExpression(unwrapped)) {
    const values = []
    for (const element of unwrapped.elements) {
      if (ts.isSpreadElement(element)) {
        const spread = resolveArrayLike(context, file, element.expression)
        if (!spread) return { ok: false }
        for (const item of spread) {
          const evaluated = evaluateExpression(context, file, item, depth + 1)
          if (!evaluated.ok) return { ok: false }
          values.push(evaluated.value)
        }
        continue
      }
      const evaluated = evaluateExpression(context, file, element, depth + 1)
      if (!evaluated.ok) return { ok: false }
      values.push(evaluated.value)
    }
    return { ok: true, value: values }
  }
  if (ts.isObjectLiteralExpression(unwrapped)) {
    const object = {}
    for (const property of unwrapped.properties) {
      if (ts.isPropertyAssignment(property)) {
        const key = propertyKeyText(
          property.name,
          sourceFile ?? property.getSourceFile()
        )
        if (!key) return { ok: false }
        const evaluated = evaluateExpression(
          context,
          file,
          property.initializer,
          depth + 1
        )
        if (!evaluated.ok) return { ok: false }
        object[key] = evaluated.value
      } else if (
        ts.isPropertyAssignment(property) ||
        ts.isSpreadAssignment(property)
      ) {
        return { ok: false }
      } else {
        return { ok: false }
      }
    }
    return { ok: true, value: object }
  }
  if (ts.isIdentifier(unwrapped)) {
    if (unwrapped.text === 'undefined') return { ok: true, value: null }
    if (unwrapped.text === 'NaN') return { ok: true, value: null }
    if (unwrapped.text === 'Infinity') return { ok: false }
    const resolved = resolveSymbol(context, sourceFile, unwrapped.text, 'value')
    if (resolved) {
      return evaluateExpression(
        context,
        resolved.file,
        resolved.node.initializer,
        depth + 1
      )
    }
    return { ok: false }
  }
  if (ts.isPropertyAccessExpression(unwrapped)) {
    const text = unwrapped.getText(sourceFile ?? undefined)
    const known = {
      'Number.MAX_SAFE_INTEGER': Number.MAX_SAFE_INTEGER,
      'Number.MIN_SAFE_INTEGER': Number.MIN_SAFE_INTEGER,
      'Number.MAX_VALUE': Number.MAX_VALUE,
      'Number.EPSILON': Number.EPSILON,
    }
    if (Object.prototype.hasOwnProperty.call(known, text))
      return { ok: true, value: known[text] }
    return { ok: false }
  }
  if (ts.isCallExpression(unwrapped)) {
    // `Object.freeze([...])` and similar pure wrappers around a literal.
    if (unwrapped.arguments.length === 1) {
      const evaluated = evaluateExpression(
        context,
        file,
        unwrapped.arguments[0],
        depth + 1
      )
      if (evaluated.ok) return evaluated
    }
    return { ok: false }
  }
  return { ok: false }
}

/* -------------------------------------------------------------------------- */
/* Kind inference from TS type text (fallback when schemastery is unavailable) */
/* -------------------------------------------------------------------------- */

function kindFromTypeText(typeText, volatile) {
  const result = { kind: 'json', enumValues: [], nullable: false, volatile }
  if (!typeText) return result
  let text = typeText.replace(/\s+/g, ' ').trim()
  if (/^readonly\s+/.test(text)) text = text.replace(/^readonly\s+/, '')
  const volatileMatch = text.match(/^Volatile\s*<([\s\S]+)>$/)
  if (volatileMatch) {
    text = volatileMatch[1].trim()
    result.volatile = true
  }
  const parts = splitTopLevelUnion(text)
  const nonNull = parts.filter(part => part !== 'null' && part !== 'undefined')
  if (parts.includes('null')) result.nullable = true
  if (nonNull.length === 0) return result
  if (nonNull.length > 1) {
    if (nonNull.every(part => /^'.*'$/.test(part) || /^".*"$/.test(part))) {
      result.kind = 'enum'
      result.enumValues = nonNull.map(part => part.slice(1, -1))
      return result
    }
    return result
  }
  const single = nonNull[0]
  if (single === 'string') result.kind = 'string'
  else if (single === 'number') result.kind = 'number'
  else if (single === 'boolean') result.kind = 'boolean'
  else if (/^'.*'$/.test(single) || /^".*"$/.test(single)) {
    result.kind = 'enum'
    result.enumValues = [single.slice(1, -1)]
  }
  return result
}

function splitTopLevelUnion(text) {
  const parts = []
  let depth = 0
  let quote = null
  let current = ''
  for (let index = 0; index < text.length; index += 1) {
    const char = text[index]
    if (quote) {
      current += char
      if (char === '\\') {
        current += text[++index] ?? ''
      } else if (char === quote) {
        quote = null
      }
      continue
    }
    if (char === '"' || char === "'" || char === '`') {
      quote = char
      current += char
      continue
    }
    if (char === '<' || char === '(' || char === '{' || char === '[') depth += 1
    if (char === '>' || char === ')' || char === '}' || char === ']') depth -= 1
    if (char === '|' && depth === 0) {
      parts.push(current.trim())
      current = ''
      continue
    }
    current += char
  }
  if (current.trim()) parts.push(current.trim())
  return parts
}


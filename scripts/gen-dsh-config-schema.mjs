const JS_TAG = {
  tag: 'tag:yaml.org,2002:js',
  resolve: value => ({ $js: String(value) }),
}

function loadPatchFile(context, path) {
  if (!existsSync(path)) throw new Error(`Patch file not found: ${path}`)
  const text = readFileSync(path, 'utf8')
  let parsed
  try {
    parsed = parseYaml(text, { customTags: [JS_TAG] })
  } catch (error) {
    throw new Error(`Failed to parse ${path}: ${error.message}`)
  }
  if (parsed === null || parsed === undefined) return []
  if (!Array.isArray(parsed))
    throw new Error(`Patch document is not a YAML sequence: ${path}`)
  return parsed
}

function convertJsMarkers(value) {
  if (Array.isArray(value)) return value.map(convertJsMarkers)
  if (value && typeof value === 'object') {
    if (Object.keys(value).length === 1 && typeof value.$js === 'string') {
      return { $js: value.$js }
    }
    const out = {}
    for (const [key, inner] of Object.entries(value))
      out[key] = convertJsMarkers(inner)
    return out
  }
  if (typeof value === 'string' && value.startsWith('!!js ')) {
    return { $js: value.slice('!!js '.length) }
  }
  return value
}

function evaluateDisabledExpression(expression, profile, os) {
  const profileContext = { name: profile }
  const fakeProcess = {
    platform: os,
    env: {},
    cwd: () => '/',
    version: '0.0.0',
    versions: {},
    argv: [],
  }
  const ctx = {
    get: key => (key === 'profileContext' ? profileContext : undefined),
  }
  const dshHomePath = subPath =>
    `~/.dsh/${String(subPath ?? '').replace(/^\/+/, '')}`
  const evaluator = new Function(
    'ctx',
    'process',
    'dshHomePath',
    `"use strict"; return (${expression});`
  )
  return evaluator(ctx, fakeProcess, dshHomePath)
}

function evaluateDisabled(raw) {
  const matrix = {}
  let failure = null
  if (typeof raw === 'boolean') {
    for (const profile of PROFILES) {
      matrix[profile] = {}
      for (const os of OSES) matrix[profile][os] = raw
    }
    return { matrix, failure }
  }
  let expression = null
  if (raw && typeof raw === 'object' && typeof raw.$js === 'string')
    expression = raw.$js
  else if (typeof raw === 'string' && raw.startsWith('!!js '))
    expression = raw.slice('!!js '.length)
  if (expression === null) {
    const truthy = Boolean(raw)
    for (const profile of PROFILES) {
      matrix[profile] = {}
      for (const os of OSES) matrix[profile][os] = truthy
    }
    return { matrix, failure }
  }
  for (const profile of PROFILES) {
    matrix[profile] = {}
    for (const os of OSES) {
      try {
        matrix[profile][os] = Boolean(
          evaluateDisabledExpression(expression, profile, os)
        )
      } catch (error) {
        matrix[profile][os] = false
        failure = { expression, error: String(error?.message ?? error) }
      }
    }
  }
  return { matrix, failure }
}

function normalizePatchRow(context, raw) {
  if (
    !raw ||
    typeof raw !== 'object' ||
    raw.id === undefined ||
    raw.id === null
  )
    return null
  const row = { id: String(raw.id) }
  if (typeof raw.name === 'string' && raw.name.length > 0) row.name = raw.name
  if (Object.prototype.hasOwnProperty.call(raw, 'config'))
    row.config = convertJsMarkers(raw.config)
  if (Object.prototype.hasOwnProperty.call(raw, 'disabled')) {
    const { matrix, failure } = evaluateDisabled(raw.disabled)
    row.disabledByProfileOs = matrix
    if (failure) {
      row.disableNote = failure.expression
      context.stats.disabledEvalFailures += 1
      context.warnings.push(
        `disabled expression evaluation failed in ${row.id}: ${failure.expression} (${failure.error})`
      )
    }
    context.stats.disabledRows += 1
  }
  return row
}

function buildBundles(context) {
  const bundles = {}
  for (const bundleName of BUNDLE_PACKAGES) {
    const dir = context.packageIndex.get(bundleName)
    if (!dir)
      throw new Error(`Bundle package not found in DSH checkout: ${bundleName}`)
    const pkg = packageJsonOf(context, dir)
    const declared = pkg?.dsh?.bundle?.patch
    if (!declared)
      throw new Error(`${bundleName} package.json has no dsh.bundle.patch`)
    const patchList = Array.isArray(declared) ? declared : [declared]
    const rows = []
    for (const relativePath of patchList) {
      const patchPath = join(dir, relativePath)
      const document = loadPatchFile(context, patchPath)
      for (const entry of document) {
        if (!entry || typeof entry !== 'object') continue
        if (Array.isArray(entry.insert)) {
          for (const item of entry.insert) {
            const row = normalizePatchRow(context, item)
            if (row) rows.push(row)
          }
          continue
        }
        const row = normalizePatchRow(context, entry)
        if (row) rows.push(row)
      }
    }
    bundles[bundleName] = { entries: rows }
    context.stats.bundleRowCounts[bundleName] = rows.length
  }
  return bundles
}


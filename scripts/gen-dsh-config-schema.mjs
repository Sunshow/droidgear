function typeFieldFromMember(context, member, sourceFile) {
  if (!ts.isPropertySignature(member)) return null
  const name = propertyKeyText(member.name, sourceFile)
  if (!name) return null
  const typeNode = member.type
  const typeText = textOf(typeNode, sourceFile).replace(/\s+/g, ' ').trim()
  return {
    name,
    optional: Boolean(member.questionToken),
    typeText,
    doc: jsdocText(member),
    volatile: /^Volatile\s*</.test(typeText),
  }
}

function createTypeCollector(context) {
  return {
    fields: new Map(),
    files: new Set(),
    visited: new Set(),
    /** Resolve a type reference `name` from `file` and merge its fields. */
    collectTypeReference(file, name, depth) {
      if (depth > 8) return
      const key = `${file}:${name}`
      if (this.visited.has(key)) return
      this.visited.add(key)
      const sourceFile = parseSourceFile(context, file)
      if (!sourceFile) return
      let node = findLocalTypeDeclaration(context, sourceFile, name)
      let nodeFile = file
      let nodeSource = sourceFile
      if (!node) {
        const resolved = resolveSymbol(context, sourceFile, name, 'type')
        if (!resolved) return
        node = resolved.node
        nodeFile = resolved.file
        nodeSource = parseSourceFile(context, nodeFile)
        if (!nodeSource) return
      }
      this.files.add(nodeFile)
      if (ts.isInterfaceDeclaration(node)) {
        for (const member of node.members ?? []) {
          const field = typeFieldFromMember(context, member, nodeSource)
          if (field && !this.fields.has(field.name))
            this.fields.set(field.name, field)
        }
        for (const heritage of node.heritageClauses ?? []) {
          if (heritage.token !== ts.SyntaxKind.ExtendsKeyword) continue
          for (const type of heritage.types)
            this.collectHeritage(nodeFile, type, depth + 1)
        }
        return
      }
      if (ts.isTypeAliasDeclaration(node)) {
        this.collectTypeNode(nodeFile, node.type, depth + 1)
        return
      }
      if (ts.isClassDeclaration(node)) {
        for (const member of node.members ?? []) {
          if (ts.isPropertyDeclaration(member)) {
            const fieldName = propertyKeyText(member.name, nodeSource)
            if (!fieldName) continue
            const typeText = textOf(member.type, nodeSource)
              .replace(/\s+/g, ' ')
              .trim()
            if (!this.fields.has(fieldName)) {
              this.fields.set(fieldName, {
                name: fieldName,
                optional: Boolean(member.questionToken),
                typeText,
                doc: jsdocText(member),
                volatile: /^Volatile\s*</.test(typeText),
              })
            }
          }
        }
      }
    },
    /**
     * Merge a heritage/utility reference. Utility types (`Omit`, `Pick`,
     * `Partial`, `Required`, `Readonly`) are resolved field-wise so declarations
     * such as `interface Config extends Omit<ProtocolConfig, 'models'>` keep their
     * inherited fields.
     */
    collectHeritage(file, typeNode, depth) {
      if (depth > 8) return
      const node = unwrap(typeNode)
      const expression = ts.isExpressionWithTypeArguments(node)
        ? node.expression
        : ts.isTypeReferenceNode(node)
          ? node.typeName
          : null
      if (!expression || !ts.isIdentifier(expression)) return
      const typeArguments = node.typeArguments
      const utilities = new Set([
        'Omit',
        'Pick',
        'Partial',
        'Required',
        'Readonly',
      ])
      if (
        utilities.has(expression.text) &&
        typeArguments &&
        typeArguments.length > 0
      ) {
        const inner = createTypeCollector(context)
        inner.collectTypeNode(file, typeArguments[0], depth + 1)
        let fields = new Map(inner.fields)
        if (
          (expression.text === 'Omit' || expression.text === 'Pick') &&
          typeArguments[1]
        ) {
          const keys = literalTypeKeys(typeArguments[1])
          if (keys) {
            if (expression.text === 'Omit')
              for (const key of keys) fields.delete(key)
            else
              for (const key of [...fields.keys()])
                if (!keys.has(key)) fields.delete(key)
          } else if (expression.text === 'Pick') {
            fields = new Map()
          }
        }
        for (const field of fields.values()) {
          if (!this.fields.has(field.name)) this.fields.set(field.name, field)
        }
        for (const innerFile of inner.files) this.files.add(innerFile)
        return
      }
      this.collectTypeReference(file, expression.text, depth + 1)
    },
    collectTypeNode(file, node, depth) {
      if (!node || depth > 8) return
      const unwrapped = unwrap(node)
      if (ts.isTypeReferenceNode(unwrapped)) {
        const typeName = unwrapped.typeName
        if (ts.isIdentifier(typeName)) {
          this.collectTypeReference(file, typeName.text, depth + 1)
        }
        return
      }
      if (
        ts.isIntersectionTypeNode(unwrapped) ||
        ts.isUnionTypeNode(unwrapped)
      ) {
        for (const part of unwrapped.types)
          this.collectTypeNode(file, part, depth + 1)
        return
      }
      if (ts.isTypeLiteralNode(unwrapped)) {
        const sourceFile = parseSourceFile(context, file)
        if (!sourceFile) return
        this.files.add(file)
        for (const member of unwrapped.members) {
          const field = typeFieldFromMember(context, member, sourceFile)
          if (field && !this.fields.has(field.name))
            this.fields.set(field.name, field)
        }
      }
    },
  }
}

function unwrapTypeReference(typeNode) {
  const node = unwrap(typeNode)
  if (ts.isTypeReferenceNode(node) && ts.isIdentifier(node.typeName))
    return node.typeName.text
  if (
    ts.isExpressionWithTypeArguments(node) &&
    ts.isIdentifier(node.expression)
  ) {
    return node.expression.text
  }
  return null
}

/** Extract the string-literal keys from `Omit<T, 'a' | 'b'>`-style type arguments. */
function literalTypeKeys(node) {
  const unwrapped = unwrap(node)
  const keys = new Set()
  const collect = candidate => {
    const inner = unwrap(candidate)
    if (ts.isLiteralTypeNode(inner) && ts.isStringLiteral(inner.literal)) {
      keys.add(inner.literal.text)
      return true
    }
    if (ts.isUnionTypeNode(inner)) {
      return inner.types.every(part => collect(part))
    }
    return false
  }
  return collect(unwrapped) ? keys : null
}

function resolveCatalogType(context, pkgName, section) {
  const collector = createTypeCollector(context)
  const sourcePath = join(context.dshRoot, section.sourcePath)
  const sourceFile = existsSync(sourcePath)
    ? parseSourceFile(context, sourcePath)
    : null
  let declaration = null
  let declarationName = null
  if (sourceFile) {
    declaration = findDeclarationAtLine(context, sourceFile, section.sourceLine)
    if (declaration?.name) declarationName = declaration.name.text
  }
  if (declaration) {
    const node = declaration
    if (ts.isInterfaceDeclaration(node)) {
      const doc = jsdocText(node)
      for (const member of node.members ?? []) {
        const field = typeFieldFromMember(context, member, sourceFile)
        if (field && !collector.fields.has(field.name))
          collector.fields.set(field.name, field)
      }
      for (const heritage of node.heritageClauses ?? []) {
        for (const type of heritage.types)
          collector.collectHeritage(sourcePath, type, 0)
      }
      collector.files.add(sourcePath)
      return {
        doc,
        fields: collector.fields,
        files: collector.files,
        declarationName,
        sourcePath,
      }
    }
    if (ts.isTypeAliasDeclaration(node)) {
      const doc = jsdocText(node)
      collector.files.add(sourcePath)
      collector.collectTypeNode(sourcePath, node.type, 0)
      // `export type Config = ImportedConfig` has no own fields; follow the alias.
      const alpha = unwrap(node.type)
      if (ts.isTypeReferenceNode(alpha)) {
        const ref = unwrapTypeReference(alpha)
        if (ref) collector.collectTypeReference(sourcePath, ref, 0)
      }
      return {
        doc,
        fields: collector.fields,
        files: collector.files,
        declarationName,
        sourcePath,
      }
    }
    if (ts.isClassDeclaration(node)) {
      const doc = jsdocText(node)
      collector.fields.clear()
      collector.files.add(sourcePath)
      for (const member of node.members ?? []) {
        if (!ts.isPropertyDeclaration(member)) continue
        const name = propertyKeyText(member.name, sourceFile)
        if (!name) continue
        const typeText = textOf(member.type, sourceFile)
          .replace(/\s+/g, ' ')
          .trim()
        collector.fields.set(name, {
          name,
          optional: Boolean(member.questionToken),
          typeText,
          doc: jsdocText(member),
          volatile: /^Volatile\s*</.test(typeText),
        })
      }
      return {
        doc,
        fields: collector.fields,
        files: collector.files,
        declarationName,
        sourcePath,
      }
    }
  }

  // Fall back to the generated code block: prefer `Config`, then `*Config`.
  const parsed = catalogCodeInterfaces(context, pkgName, section.code)
  const candidates = [...parsed.interfaces.entries()]
  const preferred =
    parsed.interfaces.get('Config') ??
    candidates.find(([name]) => /Config$/.test(name))?.[1] ??
    candidates[0]?.[1]
  if (preferred) {
    const node = preferred.node
    const doc = jsdocText(node)
    const syntheticFile = parsed.sourceFile
    for (const member of node.members ?? []) {
      const field = typeFieldFromMember(context, member, syntheticFile)
      if (field && !collector.fields.has(field.name))
        collector.fields.set(field.name, field)
    }
    for (const heritage of node.heritageClauses ?? []) {
      for (const type of heritage.types) {
        const refNode = unwrap(type.type)
        if (
          ts.isTypeReferenceNode(refNode) &&
          ts.isIdentifier(refNode.typeName)
        ) {
          const local = parsed.interfaces.get(refNode.typeName.text)
          if (local) {
            for (const member of local.node.members ?? []) {
              const field = typeFieldFromMember(context, member, syntheticFile)
              if (field && !collector.fields.has(field.name))
                collector.fields.set(field.name, field)
            }
          }
        }
      }
    }
    collector.files.add(sourcePath)
    return {
      doc,
      fields: collector.fields,
      files: collector.files,
      declarationName: 'Config',
      sourcePath,
    }
  }
  return {
    doc: '',
    fields: new Map(),
    files: new Set(),
    declarationName: null,
    sourcePath,
  }
}

function findDeclarationAtLine(context, sourceFile, line) {
  if (!line) return null
  let result = null
  const visit = node => {
    if (result) return
    if (
      ts.isInterfaceDeclaration(node) ||
      ts.isTypeAliasDeclaration(node) ||
      ts.isClassDeclaration(node)
    ) {
      if (nodeLine(sourceFile, node) === line) result = node
    }
    if (!result) ts.forEachChild(node, visit)
  }
  visit(sourceFile)
  return result
}


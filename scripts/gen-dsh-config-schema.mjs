#!/usr/bin/env node
/* global Buffer, console, process */
/**
 * Generate `src-tauri/crates/droidgear-core/res/dsh-config-schema.json` from a
 * DeepSeek Harness (DSH) source checkout.
 *
 * Data sources (all read-only):
 *   - `<dsh>/packages/bundle/base/package.json` + `cordis.patch.yml`
 *   - `<dsh>/packages/bundle/web-app/package.json` + `cordis.patch.yml` +
 *     `presets/{standard,ptc,minimal,cordis}.patch.yml`
 *   - `<dsh>/packages/experimental/agent-team-profile/{package.json,cordis.patch.yml}`
 *   - `<dsh>/packages/experimental/auto-review/{package.json,cordis.patch.yml}`
 *     (`dsh.bundle.patch` in each package.json declares the patch file order)
 *   - `<dsh>/docs/config-catalog.zh.md` — generated TS config declarations, used
 *     for field names/types/JSDoc (it is itself generated by DSH's
 *     `scripts/gen-config-catalog.ts`, so it tracks the runtime schema).
 *   - `<dsh>/packages/<area>/<pkg>/src/*.ts` — schemastery (`@deepseek-ai/schemastery`)
 *     `Config = z.object({...})` declarations for `.default()`, `.volatile()`,
 *     `.role('secret')`, enum unions, etc.
 *
 * The JSON contract (schemaVersion/bundles/entries) is defined in
 * `/tmp/dsh-config-contract.md` (worktree copy:
 * `docs/developer/dsh-config-surfaces.zh.md`) and consumed by
 * `src-tauri/crates/droidgear-core/src/dsh_config.rs`.
 *
 * Regenerate (from the DroidGear repo root):
 *
 *   node scripts/gen-dsh-config-schema.mjs
 *   node scripts/gen-dsh-config-schema.mjs --dsh /path/to/deepseek-harness --version 0.2.1-rc.2
 *   node scripts/gen-dsh-config-schema.mjs --check     # validate committed JSON + idempotency
 *   node scripts/gen-dsh-config-schema.mjs --stats     # print extraction statistics only
 *
 * The script is deterministic apart from `generatedAt` (current UTC date): the
 * same DSH checkout always produces the same document. It never writes to the
 * DSH checkout.
 *
 * Field facts are only emitted when they can be derived from source:
 *   - `kind`/`enumValues`/`volatile`/`secret`/`nullable`/`default` come from the
 *     schemastery declaration (falling back to the catalog TS declaration, then
 *     to `kind: "json"` for anything nested — nested fields are never expanded).
 *   - `default` stays `null` when the declaration's default expression cannot be
 *     evaluated statically (e.g. it calls a function).
 *   - Entry/field `tier` is DroidGear editorial metadata (not a DSH fact); it is
 *     curated in ENTRY_TIER/FIELD_TIER below from the design doc's A/B/C split.
 *     Unknown entries/fields default to tier C (read-only, advanced page).
 *
 * `disabledByProfileOs` evaluates a row's `disabled` (`true` or `!!js <expr>`)
 * for profile ∈ {desktop, web} × os ∈ {darwin, win32, linux}. Expressions run
 * with `process.platform` set per-OS, an empty `process.env`, a minimal
 * `ctx.get('profileContext')` object and a `dshHomePath()` helper. An
 * expression that throws leaves all six cells `false` and records the raw
 * expression in `disableNote` (never guessed).
 */


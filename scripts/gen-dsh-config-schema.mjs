function rowDisabledFor(row, profile, os) {
  const matrix = row.disabledByProfileOs
  if (!matrix || !matrix[profile]) return false
  return Boolean(matrix[profile][os])
}

/**
 * Compose the four bundle layers for a profile/os pair and return the ids that
 * end up enabled. Mirrors DSH's last-wins row composition (including rows that
 * only patch an existing id).
 */
function composeActiveIds(bundles, profile, os) {
  const state = new Map()
  for (const bundleName of PROFILE_BUNDLES[profile]) {
    const bundle = bundles[bundleName]
    if (!bundle) continue
    for (const row of bundle.entries) {
      if (!state.has(row.id)) state.set(row.id, false)
      if (row.disabledByProfileOs)
        state.set(row.id, rowDisabledFor(row, profile, os))
    }
  }
  const active = new Set()
  for (const [id, disabled] of state) if (!disabled) active.add(id)
  return { active, order: [...state.keys()] }
}

function firstRowMetadata(context, bundles) {
  const firstRow = new Map()
  const nameById = new Map()
  for (const bundleName of BUNDLE_PACKAGES) {
    for (const row of bundles[bundleName].entries) {
      if (!firstRow.has(row.id)) firstRow.set(row.id, row)
      if (
        !nameById.has(row.id) &&
        typeof row.name === 'string' &&
        row.name.length > 0
      ) {
        nameById.set(row.id, row.name)
      }
    }
  }
  return { firstRow, nameById }
}

function buildEntries(context, bundles) {
  const { firstRow, nameById } = firstRowMetadata(context, bundles)
  const activeByProfileOs = {}
  let activeAnywhere = new Set()
  for (const profile of PROFILES) {
    activeByProfileOs[profile] = {}
    for (const os of OSES) {
      const { active, order } = composeActiveIds(bundles, profile, os)
      activeByProfileOs[profile][os] = { active, order }
      activeAnywhere = new Set([...activeAnywhere, ...active])
    }
  }

  // Keep bundle order for deterministic diffs; only entries enabled somewhere
  // get metadata (an entry disabled in every profile/os is preset-provided or
  // host-internal and intentionally not offered as a configurable row).
  const orderedIds = []
  for (const bundleName of BUNDLE_PACKAGES) {
    for (const row of bundles[bundleName].entries) {
      if (!orderedIds.includes(row.id)) orderedIds.push(row.id)
    }
  }
  const entries = {}
  const included = []
  for (const id of orderedIds) {
    if (!activeAnywhere.has(id)) continue
    const row = firstRow.get(id)
    const declaredName = nameById.get(id) ?? ''
    const packageName =
      resolvePackageName(context, declaredName) ?? declaredName
    const config = declaredName
      ? resolveConfigForEntry(context, declaredName)
      : null
    const pkgJson =
      packageName && context.packageIndex.has(packageName)
        ? packageJsonOf(context, context.packageIndex.get(packageName))
        : null
    const tier = ENTRY_TIER[id] ?? 'C'
    const description =
      cleanDoc(config?.doc) || cleanDoc(pkgJson?.description) || ''
    const fields = (config?.fields ?? []).map(field => ({
      name: field.name,
      kind: field.kind,
      default: field.default,
      nullable: field.nullable,
      enumValues: field.enumValues,
      volatile: field.volatile,
      secret: field.secret,
      tier: FIELD_TIER[id]?.[field.name] ?? tier,
      description: field.description,
    }))
    entries[id] = { package: packageName, tier, description, fields }
    included.push(id)
    if (fields.length > 0) context.stats.entriesWithFields += 1
    else if (packageName && loadCatalog(context).has(packageName)) {
      context.stats.noFieldPackages.push(`${id} (${packageName})`)
    }
    for (const field of fields) {
      context.stats.fieldCount += 1
      context.stats.fieldKinds[field.kind] =
        (context.stats.fieldKinds[field.kind] ?? 0) + 1
      context.stats.fieldTiers[field.tier] =
        (context.stats.fieldTiers[field.tier] ?? 0) + 1
      if (field.volatile) context.stats.volatileFields += 1
      if (field.secret) context.stats.secretFields += 1
    }
    void row
  }
  context.stats.entryCount = included.length
  context.stats.entryTiers = included.reduce((acc, id) => {
    const tier = entries[id].tier
    acc[tier] = (acc[tier] ?? 0) + 1
    return acc
  }, {})
  context.stats.entriesByProfileOs = Object.fromEntries(
    Object.entries(activeByProfileOs).map(([profile, byOs]) => [
      profile,
      Object.fromEntries(
        Object.entries(byOs).map(([os, { active }]) => [os, active.size])
      ),
    ])
  )
  return { entries, activeByProfileOs }
}


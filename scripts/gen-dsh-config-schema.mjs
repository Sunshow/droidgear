function parseArgs(argv) {
  const options = {
    dsh: DEFAULT_DSH_REPO,
    version: null,
    out: DEFAULT_OUT_PATH,
    check: false,
    stats: false,
    help: false,
  }
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    switch (arg) {
      case '--dsh':
        options.dsh = argv[++index]
        break
      case '--version':
        options.version = argv[++index]
        break
      case '--out':
        options.out = resolve(argv[++index])
        break
      case '--check':
        options.check = true
        break
      case '--stats':
        options.stats = true
        break
      case '--help':
      case '-h':
        options.help = true
        break
      default:
        throw new Error(`Unknown argument: ${arg}`)
    }
  }
  return options
}


function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'))
}

/** Local calendar date (`YYYY-MM-DD`), matching the contract's `generatedAt` sample. */
function formatLocalDate(date) {
  const pad = value => String(value).padStart(2, '0')
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`
}

function nodeLine(sourceFile, node) {
  return (
    sourceFile.getLineAndCharacterOfPosition(node.getStart(sourceFile)).line + 1
  )
}

function textOf(node, sourceFile) {
  return node === undefined ? '' : node.getText(sourceFile)
}

function unwrap(node) {
  let current = node
  for (;;) {
    if (!current) return current
    if (
      ts.isParenthesizedExpression(current) ||
      ts.isAsExpression(current) ||
      ts.isNonNullExpression(current) ||
      ts.isTypeAssertionExpression(current) ||
      (typeof ts.isSatisfiesExpression === 'function' &&
        ts.isSatisfiesExpression(current))
    ) {
      current = current.expression
      continue
    }
    return current
  }
}

function cleanDoc(raw) {
  if (!raw) return ''
  return raw
    .replace(/\{@link(?:code|plain)?\s+([^}|]+)(?:\|[^}]*)?\}/g, '$1')
    .replace(/\s+/g, ' ')
    .trim()
}

function commentText(comment) {
  if (typeof comment === 'string') return comment
  if (Array.isArray(comment)) {
    return comment
      .map(part => (typeof part.text === 'string' ? part.text : ''))
      .join('')
  }
  return ''
}

function jsdocText(node) {
  const docs = []
  if (Array.isArray(node.jsDoc)) docs.push(...node.jsDoc)
  else {
    for (const entry of ts.getJSDocCommentsAndTags(node)) {
      if (entry.kind === ts.SyntaxKind.JSDoc) docs.push(entry)
    }
  }
  return cleanDoc(docs.map(doc => commentText(doc.comment)).join(' '))
}

function hasExportModifier(node) {
  return Boolean(
    node.modifiers?.some(
      modifier => modifier.kind === ts.SyntaxKind.ExportKeyword
    )
  )
}

function propertyKeyText(name, sourceFile) {
  if (!name) return null
  if (
    ts.isIdentifier(name) ||
    ts.isStringLiteral(name) ||
    ts.isNumericLiteral(name)
  ) {
    return name.text
  }
  if (ts.isComputedPropertyName(name)) return null
  return name.getText(sourceFile)
}


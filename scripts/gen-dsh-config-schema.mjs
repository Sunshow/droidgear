/**
 * Index every workspace package name -> absolute dir. Depth-limited walk over
 * the DSH checkout (skips node_modules and build output).
 */
function buildPackageIndex(root) {
  const index = new Map()
  const skip = new Set([
    'node_modules',
    '.git',
    'dist',
    'lib',
    'coverage',
    'build',
    'out',
  ])
  const walk = (dir, depth) => {
    if (depth > 4) return
    let entries
    try {
      entries = readdirSync(dir)
    } catch {
      return
    }
    if (entries.includes('package.json')) {
      try {
        const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
        if (typeof pkg.name === 'string' && !index.has(pkg.name))
          index.set(pkg.name, dir)
      } catch {
        /* ignore malformed package.json */
      }
    }
    for (const entry of entries) {
      if (skip.has(entry) || entry.startsWith('.')) continue
      const full = join(dir, entry)
      let stat
      try {
        stat = statSync(full)
      } catch {
        continue
      }
      if (stat.isDirectory()) walk(full, depth + 1)
    }
  }
  walk(root, 0)
  return index
}

function parseSourceFile(context, path) {
  const cached = context.tsCaches.get(path)
  if (cached) return cached
  let sourceFile
  try {
    const text = readFileSync(path, 'utf8')
    sourceFile = ts.createSourceFile(
      path,
      text,
      ts.ScriptTarget.Latest,
      true,
      scriptKindFor(path)
    )
  } catch {
    sourceFile = null
  }
  context.tsCaches.set(path, sourceFile)
  return sourceFile
}

function scriptKindFor(path) {
  if (path.endsWith('.tsx')) return ts.ScriptKind.TSX
  if (path.endsWith('.mts') || path.endsWith('.cts')) return ts.ScriptKind.TS
  return ts.ScriptKind.TS
}

/** Package dir owning a file (nearest ancestor package.json), cached. */
function packageDirOfFile(context, filePath) {
  const cached = context.pkgDirByFile.get(filePath)
  if (cached) return cached
  let dir = dirname(filePath)
  for (let depth = 0; depth < 8; depth += 1) {
    if (existsSync(join(dir, 'package.json'))) {
      context.pkgDirByFile.set(filePath, dir)
      return dir
    }
    const parent = dirname(dir)
    if (parent === dir) break
    dir = parent
  }
  context.pkgDirByFile.set(filePath, null)
  return null
}

function packageJsonOf(context, pkgDir) {
  const cached = context.packageJsonCache.get(pkgDir)
  if (cached) return cached
  let parsed = null
  try {
    parsed = readJson(join(pkgDir, 'package.json'))
  } catch {
    parsed = null
  }
  context.packageJsonCache.set(pkgDir, parsed)
  return parsed
}

function resolvePackageName(context, specifier) {
  if (typeof specifier !== 'string' || specifier.length === 0) return null
  if (context.packageIndex.has(specifier)) return specifier
  const segments = specifier.split('/')
  for (let take = segments.length - 1; take >= 2; take -= 1) {
    const candidate = segments.slice(0, take).join('/')
    if (context.packageIndex.has(candidate)) return candidate
  }
  return null
}

function listTsFiles(dir, options = {}) {
  const skipDirs = new Set([
    'node_modules',
    '.git',
    'tests',
    '__tests__',
    'test',
    'lib',
    'dist',
    'coverage',
    'locales',
  ])
  const files = []
  const walk = current => {
    let entries
    try {
      entries = readdirSync(current)
    } catch {
      return
    }
    for (const entry of entries) {
      if (skipDirs.has(entry) || entry.startsWith('.')) continue
      const full = join(current, entry)
      let stat
      try {
        stat = statSync(full)
      } catch {
        continue
      }
      if (stat.isDirectory()) {
        walk(full)
        continue
      }
      if (!/\.(ts|mts)$/.test(entry) || entry.endsWith('.d.ts')) continue
      if (/\.(test|spec)\.ts$/.test(entry)) continue
      files.push(full)
    }
  }
  walk(dir)
  if (options.limit) return files.slice(0, options.limit)
  return files
}


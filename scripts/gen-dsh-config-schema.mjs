function formatStats(context) {
  const bundles = Object.entries(context.stats.bundleRowCounts).map(
    ([name, count]) => `${name}=${count}`
  )
  const lines = []
  lines.push(`DSH version: ${context.version}`)
  lines.push(`bundle rows: ${bundles.join(', ')}`)
  lines.push(
    `bundle rows total: ${Object.values(context.stats.bundleRowCounts).reduce((a, b) => a + b, 0)}`
  )
  lines.push(`entries (metadata): ${context.stats.entryCount}`)
  lines.push(
    `active per profile/os: ${JSON.stringify(context.stats.entriesByProfileOs)}`
  )
  lines.push(`entries with fields: ${context.stats.entriesWithFields}`)
  lines.push(
    `fields: ${context.stats.fieldCount} ${JSON.stringify(context.stats.fieldKinds)}`
  )
  lines.push(`field tiers: ${JSON.stringify(context.stats.fieldTiers)}`)
  lines.push(`entry tiers: ${JSON.stringify(context.stats.entryTiers)}`)
  lines.push(
    `volatile fields: ${context.stats.volatileFields}; secret fields: ${context.stats.secretFields}`
  )
  lines.push(
    `rows declaring disabled: ${context.stats.disabledRows}; eval failures: ${context.stats.disabledEvalFailures}`
  )
  if (context.stats.schemaFallbackPackages.length > 0) {
    lines.push(
      `packages using TS-declaration fallback (no schema match): ${context.stats.schemaFallbackPackages.length}`
    )
    lines.push(`  ${context.stats.schemaFallbackPackages.join(', ')}`)
  }
  if (context.stats.noFieldPackages.length > 0) {
    lines.push(
      `config-bearing entries without extracted fields: ${context.stats.noFieldPackages.length}`
    )
    lines.push(`  ${context.stats.noFieldPackages.join(', ')}`)
  }
  if (context.warnings.length > 0) {
    lines.push(`warnings: ${context.warnings.length}`)
    for (const warning of context.warnings.slice(0, 40))
      lines.push(`  - ${warning}`)
  }
  return lines.join('\n')
}

function summarizeDocument(document) {
  const bundleCounts = Object.fromEntries(
    Object.entries(document.bundles).map(([name, bundle]) => [
      name,
      bundle.entries.length,
    ])
  )
  const fieldCount = Object.values(document.entries).reduce(
    (total, entry) => total + entry.fields.length,
    0
  )
  return {
    dshVersion: document.dshVersion,
    bundleCounts,
    entryCount: Object.keys(document.entries).length,
    fieldCount,
    sizeBytes: Buffer.byteLength(serializeDocument(document), 'utf8'),
  }
}

function validateGenerated(context, document) {
  const problems = []
  const expectedBundles = BUNDLE_PACKAGES
  for (const bundleName of expectedBundles) {
    if (!document.bundles[bundleName])
      problems.push(`missing bundle ${bundleName}`)
  }
  if (Object.keys(document.bundles).length !== expectedBundles.length) {
    problems.push(
      `unexpected bundle keys: ${Object.keys(document.bundles).join(', ')}`
    )
  }

  let rowsWithDisabled = 0
  for (const [bundleName, bundle] of Object.entries(document.bundles)) {
    for (const row of bundle.entries) {
      if (!row.id) problems.push(`${bundleName}: row without id`)
      if (row.disabledByProfileOs) {
        rowsWithDisabled += 1
        for (const profile of PROFILES) {
          const byOs = row.disabledByProfileOs[profile]
          if (!byOs) {
            problems.push(`${bundleName}/${row.id}: missing profile ${profile}`)
            continue
          }
          for (const os of OSES) {
            if (typeof byOs[os] !== 'boolean') {
              problems.push(
                `${bundleName}/${row.id}: ${profile}.${os} is not boolean`
              )
            }
          }
        }
        if (
          row.disableNote &&
          Object.values(row.disabledByProfileOs).some(byOs =>
            Object.values(byOs).some(Boolean)
          )
        ) {
          problems.push(
            `${bundleName}/${row.id}: disableNote present but some cells are true`
          )
        }
      }
      if (row.config && containsJsMarker(row.config) === false) {
        // no-op: configs may legitimately have no !!js markers
      }
    }
  }

  const serialized = serializeDocument(document)
  if (serialized.includes('!!js'))
    problems.push('raw !!js remains in generated JSON')
  if (/"\$js":\s*""/.test(serialized))
    problems.push('empty $js expression in generated JSON')

  const allowedKinds = new Set(['string', 'number', 'boolean', 'enum', 'json'])
  let fieldCount = 0
  for (const [id, entry] of Object.entries(document.entries)) {
    if (!entry.package) problems.push(`entry ${id}: missing package`)
    if (!['A', 'B', 'C'].includes(entry.tier))
      problems.push(`entry ${id}: invalid tier ${entry.tier}`)
    for (const field of entry.fields) {
      fieldCount += 1
      if (!allowedKinds.has(field.kind))
        problems.push(`entry ${id}.${field.name}: invalid kind ${field.kind}`)
      if (field.kind === 'enum' && field.enumValues.length === 0) {
        problems.push(`entry ${id}.${field.name}: enum without values`)
      }
      if (field.kind !== 'enum' && field.enumValues.length > 0) {
        problems.push(`entry ${id}.${field.name}: enumValues on non-enum field`)
      }
      if (
        typeof field.volatile !== 'boolean' ||
        typeof field.secret !== 'boolean'
      ) {
        problems.push(`entry ${id}.${field.name}: non-boolean flags`)
      }
      if (!['A', 'B', 'C'].includes(field.tier)) {
        problems.push(`entry ${id}.${field.name}: invalid tier ${field.tier}`)
      }
    }
  }

  const entryCount = Object.keys(document.entries).length
  if (entryCount < 165 || entryCount > 180) {
    problems.push(`entry metadata count ${entryCount} outside expected 170±10`)
  }
  if (fieldCount < 300 || fieldCount > 380) {
    problems.push(
      `field count ${fieldCount} outside expected ~335 (353 inventory fields minus nested)`
    )
  }

  const { activeByProfileOs } = buildEntries(context, document.bundles)
  const desktopDarwin = activeByProfileOs.desktop.darwin.active.size
  if (desktopDarwin !== 170) {
    problems.push(
      `desktop/darwin active entry count ${desktopDarwin} != 170 (research baseline)`
    )
  }
  return { problems, fieldCount, entryCount, rowsWithDisabled, desktopDarwin }
}

function containsJsMarker(value) {
  if (Array.isArray(value)) return value.some(containsJsMarker)
  if (value && typeof value === 'object') {
    if (Object.keys(value).length === 1 && typeof value.$js === 'string')
      return true
    return Object.values(value).some(containsJsMarker)
  }
  return false
}

function runCheck(context, options) {
  const problems = []
  if (!existsSync(options.out)) {
    console.error(
      `FAIL: generated schema not found at ${options.out}; run without --check first`
    )
    process.exitCode = 1
    return
  }
  let existing
  try {
    existing = JSON.parse(readFileSync(options.out, 'utf8'))
  } catch (error) {
    console.error(`FAIL: ${options.out} is not valid JSON: ${error.message}`)
    process.exitCode = 1
    return
  }

  // 1. Structural contract checks on the committed file.
  if (existing.schemaVersion !== 1)
    problems.push(`schemaVersion is ${existing.schemaVersion}, expected 1`)
  if (
    typeof existing.dshVersion !== 'string' ||
    existing.dshVersion.length === 0
  ) {
    problems.push('dshVersion missing')
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(existing.generatedAt ?? ''))
    problems.push('generatedAt is not YYYY-MM-DD')
  if (
    typeof existing.generator !== 'string' ||
    !existing.generator.includes('gen-dsh-config-schema.mjs')
  ) {
    problems.push('generator field missing/incorrect')
  }
  for (const bundleName of BUNDLE_PACKAGES) {
    if (!existing.bundles?.[bundleName]?.entries)
      problems.push(`bundle ${bundleName} missing`)
  }
  const serializedExisting = JSON.stringify(existing)
  if (serializedExisting.includes('!!js'))
    problems.push('committed JSON still contains raw !!js')
  const entryIds = Object.keys(existing.entries ?? {})
  if (entryIds.length < 165 || entryIds.length > 180) {
    problems.push(`entries count ${entryIds.length} outside expected ~170`)
  }
  let fieldCount = 0
  for (const entry of Object.values(existing.entries ?? {}))
    fieldCount += entry.fields?.length ?? 0
  if (fieldCount < 300 || fieldCount > 380)
    problems.push(`fields count ${fieldCount} outside expected ~335`)
  for (const [bundleName, bundle] of Object.entries(existing.bundles ?? {})) {
    for (const row of bundle.entries ?? []) {
      if (!row.disabledByProfileOs) continue
      for (const profile of PROFILES) {
        for (const os of OSES) {
          if (typeof row.disabledByProfileOs?.[profile]?.[os] !== 'boolean') {
            problems.push(
              `${bundleName}/${row.id}: incomplete disabledByProfileOs (${profile}.${os})`
            )
          }
        }
      }
    }
  }

  // 2. Regenerate and compare (idempotency).
  const regenerated = buildDocument(context)
  const stripDate = text =>
    text.replace(/"generatedAt": "[^"]*"/, '"generatedAt": "<ignored>"')
  const expectedText = stripDate(serializeDocument(regenerated))
  const actualText = stripDate(`${JSON.stringify(existing, null, 2)}\n`)
  if (expectedText !== actualText) {
    problems.push(
      'committed JSON is stale: regenerate with `node scripts/gen-dsh-config-schema.mjs`'
    )
    const expectedLines = expectedText.split('\n')
    const actualLines = actualText.split('\n')
    let shown = 0
    for (
      let index = 0;
      index < Math.max(expectedLines.length, actualLines.length) && shown < 10;
      index += 1
    ) {
      if (expectedLines[index] !== actualLines[index]) {
        problems.push(
          `  line ${index + 1}: expected ${JSON.stringify(expectedLines[index]?.slice(0, 120))} got ${JSON.stringify(actualLines[index]?.slice(0, 120))}`
        )
        shown += 1
      }
    }
  }

  // 3. Internal consistency checks (counts/JS markers/disabled matrix).
  const validation = validateGenerated(context, regenerated)
  problems.push(...validation.problems)

  const summary = summarizeDocument(regenerated)
  if (problems.length > 0) {
    console.error('FAIL: dsh-config-schema.json validation failed')
    for (const problem of problems) console.error(`  - ${problem}`)
    process.exitCode = 1
    return
  }
  console.log(
    'OK: dsh-config-schema.json matches the DSH source and the contract'
  )
  console.log(`  bundles: ${JSON.stringify(summary.bundleCounts)}`)
  console.log(
    `  entries: ${summary.entryCount} (desktop/darwin active: ${validation.desktopDarwin})`
  )
  console.log(`  fields: ${summary.fieldCount}`)
  console.log(`  disabled rows: ${validation.rowsWithDisabled}`)
  console.log(`  size: ${summary.sizeBytes} bytes`)
}

/* -------------------------------------------------------------------------- */
/* Main                                                                       */
/* -------------------------------------------------------------------------- */

function main() {
  let options
  try {
    options = parseArgs(process.argv.slice(2))
  } catch (error) {
    console.error(error.message)
    console.error(HELP)
    process.exitCode = 2
    return
  }
  if (options.help) {
    console.log(HELP)
    return
  }
  const context = createContext(options)
  if (options.check) {
    runCheck(context, options)
    return
  }
  const document = buildDocument(context)
  if (options.stats) console.error(formatStats(context))
  const outputDir = dirname(options.out)
  mkdirSync(outputDir, { recursive: true })
  writeFileSync(options.out, serializeDocument(document), 'utf8')
  const summary = summarizeDocument(document)
  console.log(`Wrote ${options.out}`)
  console.log(`  dshVersion: ${summary.dshVersion}`)
  console.log(`  bundles: ${JSON.stringify(summary.bundleCounts)}`)
  console.log(`  entries: ${summary.entryCount}`)
  console.log(`  fields: ${summary.fieldCount}`)
  console.log(`  size: ${summary.sizeBytes} bytes`)
  if (context.warnings.length > 0) {
    console.error(
      `  extraction warnings: ${context.warnings.length} (run --stats for details)`
    )
  }
}

main()
